// Generates the Odoo seed data from src/content/defaults.ts (single source of truth).
// Usage: npm run content:export   (Node >= 22.6)
import { writeFileSync } from "node:fs";
import { COLLECTIONS, ICONS, TEXTS } from "../src/content/defaults.ts";

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const id = (k) => k.replace(/[^a-z0-9]+/gi, "_").toLowerCase();
const out = ['<?xml version="1.0" encoding="utf-8"?>', "<odoo>", '    <data noupdate="1">'];

let seq = 10;
for (const [key, [page, label, value, kind = "line"]] of Object.entries(TEXTS)) {
  out.push(`        <record id="text_${id(key)}" model="disha.site.text">`,
    `            <field name="key">${esc(key)}</field>`, `            <field name="page">${esc(page)}</field>`,
    `            <field name="label">${esc(label)}</field>`, `            <field name="kind">${kind}</field>`,
    `            <field name="value">${esc(value)}</field>`, `            <field name="default_value">${esc(value)}</field>`,
    `            <field name="sequence">${seq}</field>`, "        </record>");
  seq += 10;
}
for (const [name, { label, items }] of Object.entries(COLLECTIONS)) {
  items.forEach((it, i) => {
    out.push(`        <record id="item_${name}_${i + 1}" model="disha.site.item">`,
      `            <field name="collection">${name}</field>`, `            <field name="title">${esc(it.title)}</field>`,
      ...(it.text ? [`            <field name="text">${esc(it.text)}</field>`] : []),
      ...(it.icon ? [`            <field name="icon">${it.icon}</field>`] : []),
      `            <field name="sequence">${(i + 1) * 10}</field>`, "        </record>");
  });
}
out.push("    </data>", "</odoo>");
writeFileSync(new URL("../../odoo/disha_site_content/data/seed.xml", import.meta.url), out.join("\n") + "\n");
// Selection list for the Odoo model, so it can never drift from the site
writeFileSync(new URL("../../odoo/disha_site_content/models/_collections.py", import.meta.url),
  "# Generated by web/scripts/export-content-seed.mjs - do not edit by hand.\n" +
  `COLLECTIONS = ${JSON.stringify(Object.entries(COLLECTIONS).map(([k, v]) => [k, v.label]), null, 4)}\n` +
  `ICONS = ${JSON.stringify(ICONS.map((i) => [i, i.replace(/-/g, " ").replace(/^./, (c) => c.toUpperCase())]), null, 4)}\n`);
console.log(`Exported ${Object.keys(TEXTS).length} texts, ${Object.keys(COLLECTIONS).length} collections`);
